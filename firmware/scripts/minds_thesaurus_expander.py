def expand_trigger_words(entry: dict) -> list:
    """
    1つのガイドラインエントリから臨床トリガーワードを展開し、重複のないリストを返す
    """
    raw_triggers = set(entry.get("trigger_words", []))
    disease_name = entry.get("disease_name", "")
    icd10 = entry.get("icd10", "")

    # 1. 疾患名そのものと、主要な語幹
    if disease_name:
        raw_triggers.add(disease_name)
        cleaned = disease_name.replace("（", " ").replace("）", " ").replace("(", " ").replace(")", " ").strip()
        raw_triggers.add(cleaned)
        # 「症」「病」「炎」等の除去短縮形
        for suffix in ["症", "病", "炎", "障害", "不全"]:
            if cleaned.endswith(suffix) and len(cleaned) > len(suffix) + 1:
                raw_triggers.add(cleaned[:-len(suffix)])

    # 2. ICD-10 コード
    if icd10:
        raw_triggers.add(icd10)
        if "." in icd10:
            raw_triggers.add(icd10.split(".")[0])

    # 3. シソーラス辞書からの合致展開
    for dis_key, synonyms in CLINICAL_THESAURUS.items():
        if dis_key in disease_name or disease_name in dis_key:
            for syn in synonyms:
                raw_triggers.add(syn)

    # 4. 空文字や極端に長い単語の除外 (UTF-8 32バイト以内)
    valid_triggers = []
    for t in raw_triggers:
        t_clean = t.strip()
        if not t_clean or len(t_clean.encode('utf-8')) > 40:
            continue
        valid_triggers.append(t_clean)

    return sorted(list(set(valid_triggers)))
